import fs from 'node:fs';
import postcss from 'postcss';
import {createHash} from 'node:crypto';
const native=JSON.parse(fs.readFileSync('docs/rarity-evidence/native.json','utf8'));
const bytes=fs.readFileSync('scratch/live-update-2026-11-16/'+native.source.css);
if(createHash('sha256').update(bytes).digest('hex')!==native.source.cssSha256)throw Error('Rarity CSS source mismatch');
if(Object.keys(native.species).length!==151||native.tiers.length!==5)throw Error('Unexpected rarity catalog');
fs.writeFileSync('src/data/pokemonRarity.json',JSON.stringify({source:native.source,tiers:native.tiers,species:native.species})+'\n');
const source=postcss.parse(bytes),output=postcss.root();
source.walkRules(rule=>{
 const selectors=rule.selectors.filter(s=>s.includes('.tglow')&&!s.includes('data-theme=light'));
 if(!selectors.length)return;
 let clone=rule.clone({selector:selectors.map(s=>'.game-shell .collection-page '+s).join(',')});
 for(let p=rule.parent;p.type!=='root';p=p.parent)if(p.type==='atrule'&&p.name==='media')clone=postcss.atRule({name:'media',params:p.params,nodes:[clone]});
 output.append(clone);
});
source.walkAtRules('keyframes',rule=>{if(rule.params==='tglowBreath')output.append(rule.clone());});
fs.writeFileSync('src/styles/rarity-reference.css',`/* Generated by scripts/extract-rarity-ui.mjs; BUILD ${native.source.build}; CSS SHA256 ${native.source.cssSha256}. */\n`+output.toString());
console.log({species:151,tiers:5,rules:output.nodes.length});
