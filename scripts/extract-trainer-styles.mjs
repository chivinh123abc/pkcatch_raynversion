import fs from 'node:fs';
import postcss from 'postcss';
const source=postcss.parse(fs.readFileSync('scratch/visual-parity/reference-2026-11-14/app.7130b4d937.css','utf8')),output=postcss.root();
source.walkRules(rule=>{
 const selectors=rule.selectors.filter(selector=>/\.(?:vs-intro|vs-card|vs-face|vs-name|vs-text|boss-intro|bi-[\w-]+|tr-face|tr-win|flash-overlay)\b/.test(selector)&&!selector.includes('data-theme=light'));
 if(!selectors.length)return;
 let clone=rule.clone({selector:selectors.map(selector=>'.game-shell .battle-stage '+selector.replace(/^html\.px\s+|^\.px\s+/, '')).join(',')});
 for(let parent=rule.parent;parent.type!=='root';parent=parent.parent)if(parent.type==='atrule'&&parent.name==='media')clone=postcss.atRule({name:parent.name,params:parent.params,nodes:[clone]});
 output.append(clone);
});
// Frames generates its pixel borders at runtime rather than in the static CSS.
const frames=JSON.parse(fs.readFileSync('docs/trainer-review-2026-11-16/native-frame-rules.json','utf8'));
for(const frame of frames){
 let css=frame.css;
 for(const [name,value] of frame.vars)if(/^--fx\d+$/.test(name))css=css.replaceAll(`var(${name})`,value);
 output.append(postcss.parse(`.game-shell .battle-stage ${frame.selector}{${css}}`));
}
fs.writeFileSync('src/styles/trainer-reference.css','/* Scoped live v0.4.103 trainer presentation styles; generated by scripts/extract-trainer-styles.mjs. */\n'+output.toString());
