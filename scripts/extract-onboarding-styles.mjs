import fs from 'node:fs';
import crypto from 'node:crypto';
import postcss from 'postcss';
const file=process.argv[2]||'scratch/live-update-2026-11-16/app.3e06fa8ed6.css';
const bytes=fs.readFileSync(file), source=postcss.parse(bytes), output=postcss.root();
const wanted=/\.(?:title-fx|ti-[\w-]+|lab-[\w-]+|chen-[\w-]+|lk-[\w-]+|rc-fx|rc-title|rc-tap)\b/;
let pattern;source.walkDecls('--ball-pattern',d=>{if(!pattern&&d.parent.selector==='body')pattern=d.value;});
if(!pattern)throw Error('Pinned onboarding ball pattern not found');
output.append(postcss.rule({selector:'.onboarding-root',nodes:[postcss.decl({prop:'--onboarding-pattern',value:pattern})]}));
source.walkRules(rule=>{
 if(rule.parent.type==='atrule'&&rule.parent.name==='keyframes')return;
 const selectors=rule.selectors.filter(s=>wanted.test(s)&&!s.includes('data-theme=light')&&!s.includes(':is('));
 if(!selectors.length)return;
 let clone=rule.clone({selector:selectors.map(s=>'.onboarding-root '+s.replace(/^html\.px\s+|^\.px\s+/,'')).join(',')});
 clone.walkDecls(d=>{d.value=d.value.replaceAll('../assets/','/assets/');});
 for(let parent=rule.parent;parent.type!=='root';parent=parent.parent)if(parent.type==='atrule'&&parent.name==='media')clone=postcss.atRule({name:'media',params:parent.params,nodes:[clone]});
 output.append(clone);
});
const names=new Set();output.walkDecls(d=>{if(d.prop.startsWith('animation'))for(const word of d.value.split(/[\s,]+/))names.add(word);});
source.walkAtRules('keyframes',rule=>{if(names.has(rule.params))output.append(rule.clone());});
const hash=crypto.createHash('sha256').update(bytes).digest('hex');
fs.writeFileSync('src/styles/onboarding-reference.css',`/* Generated by scripts/extract-onboarding-styles.mjs; v0.5.02 CSS SHA256 ${hash}. */\n`+output.toString());
console.log(JSON.stringify({file,sha256:hash,rules:output.nodes.length}));
