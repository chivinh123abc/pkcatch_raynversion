import fs from 'node:fs';
import postcss from 'postcss';
import {createHash} from 'node:crypto';
const ref=JSON.parse(fs.readFileSync('docs/ui-polish-evidence/reference.json','utf8'));
const bytes=fs.readFileSync('scratch/live-update-2026-11-16/'+ref.source.css);
if(createHash('sha256').update(bytes).digest('hex')!==ref.source.cssSha256)throw Error('CSS reference changed');
const source=postcss.parse(bytes),out=postcss.root();
const wanted=/\.(?:type(?=[\s.#:[,)>+~]|$)|slot(?:[-\s.#:[,)>+~]|$)|pc-cell|pc-grid|dex-cell|dex-grid|dex-hero|dex-ring|dex-new|dex-unread|dex-last|dex-reg|dreg|team-panel|team-sets|map-region|map-head|map-sum)/;
const visual=/^(?:color|background(?:-.+)?|border(?:-.+)?|box-shadow|text-shadow|font(?:-.+)?|line-height|letter-spacing|text-transform|opacity|filter)$/;
const tokens=postcss.rule({selector:'.game-shell,.onboarding-root'});
for(const [prop,value] of Object.entries(ref.tokens))if(value)tokens.append({prop,value});out.append(tokens);
source.walkRules(rule=>{
 if(rule.parent.type==='atrule'&&rule.parent.name==='keyframes')return;
 const selectors=rule.selectors.filter(s=>wanted.test(s)&&!s.includes('data-theme=light')&&!s.includes(':root'));
 if(!selectors.length)return;
 const nodes=rule.nodes.filter(n=>n.type==='decl'&&visual.test(n.prop));if(!nodes.length)return;
 const clone=postcss.rule({selector:selectors.map(s=>{
  s=s.replace(/^html\.px\s+|^\.px\s+/,'');
  if(/\.type\b|\.mp-chips\b|\.ttl-who\b/.test(s))return '.game-shell '+s;
  return /#screen-team\b|#screen-pokedex\b/.test(s)?'.game-shell '+s:'.game-shell :is(#screen-team,#screen-pokedex) '+s;
 }).join(','),nodes:nodes.map(n=>n.clone())});
 clone.walkDecls(d=>{d.value=d.value.replaceAll('../assets/','/assets/');});
 let wrapped=clone;
 for(let p=rule.parent;p.type!=='root';p=p.parent)if(p.type==='atrule'&&['media','supports','container'].includes(p.name))wrapped=postcss.atRule({name:p.name,params:p.params,nodes:[wrapped]});
 out.append(wrapped);
});
fs.writeFileSync('src/data/typePresentation.json',JSON.stringify(ref.colors,null,2)+'\n');
fs.writeFileSync('src/data/titlePresentation.json',JSON.stringify({source:ref.source,...ref.title},null,2)+'\n');
const kebab=s=>s.replace(/[A-Z]/g,c=>'-'+c.toLowerCase());
const shared={
 '.game-shell .replica-topbar':ref.shell.header,
 '.game-shell .game-sidebar .side-nav-btn.active':ref.shell['.side-nav>button.active'],
 '.game-shell .game-sidebar .side-nav-btn:not(.active)':ref.shell['.side-nav>button:not(.active)'],
 '.game-shell .collection-page .replica-filter':ref.screens.team['.pc-filters .chip'].style,
};
for(const [selector,style] of Object.entries(shared)){
 const rule=postcss.rule({selector});
 for(const [key,value] of Object.entries(style))if(!['opacity','borderTopColor','borderTopWidth'].includes(key))rule.append({prop:kebab(key),value});
 rule.append({prop:'border',value:`${style.borderTopWidth} solid ${style.borderTopColor}`});out.append(rule);
}
for(const [source,selector] of Object.entries({'.side-nav>button.active':'.game-shell .game-sidebar .side-nav-btn.active','.pc-filters .chip':'.game-shell .collection-page .replica-filter'})){
 out.append(postcss.rule({selector,nodes:[postcss.decl({prop:'position',value:'relative'}),postcss.decl({prop:'isolation',value:'isolate'}),postcss.decl({prop:'overflow',value:'visible'})]}));
 for(const [pseudo,style] of Object.entries(ref.frames[source])){
  const rule=postcss.rule({selector:selector+pseudo});for(const [prop,value] of Object.entries(style))rule.append({prop:kebab(prop),value});out.append(rule);
 }
}
fs.writeFileSync('src/styles/ui-polish-reference.css',`/* Generated by scripts/extract-ui-polish-styles.mjs; BUILD ${ref.build}; CSS SHA256 ${ref.source.cssSha256}. Visual properties only. */\n`+out.toString());
console.log({rules:out.nodes.length,types:Object.keys(ref.colors).length});
