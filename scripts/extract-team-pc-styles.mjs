import fs from 'node:fs';
import postcss from 'postcss';
import {createHash} from 'node:crypto';
const bytes=fs.readFileSync('scratch/live-update-2026-11-16/app.3e06fa8ed6.css');
const hash=createHash('sha256').update(bytes).digest('hex');
const reference=JSON.parse(fs.readFileSync('docs/team-pc-evidence/reference.json','utf8'));
if(hash!==reference.source.css)throw Error('Team/PC reference CSS changed');
const out=postcss.root();
postcss.parse(bytes).walkRules(rule=>{
 if(rule.parent.type==='atrule'&&rule.parent.name.includes('keyframes'))return;
 const selectors=rule.selectors.filter(s=>/\.team-mini|\.pc-xp|^\.pc-sticky$|^\.shiny-mk$|^\.pc-cell \.lvl$/.test(s)&&!s.includes('data-theme=light'));
 if(!selectors.length)return;
 const clone=rule.clone({selector:selectors.map(s=>'.game-shell #screen-team '+s).join(',')});
 let wrapped=clone;for(let p=rule.parent;p.type!=='root';p=p.parent)if(p.type==='atrule'&&['media','supports'].includes(p.name))wrapped=postcss.atRule({name:p.name,params:p.params,nodes:[wrapped]});
 out.append(wrapped);
});
// The old frame extractor omitted mask composition/positions, turning the checker shadow solid.
for(const [native,local]of Object.entries({'.side-nav>button.active':'.game-shell .game-sidebar .side-nav-btn.active','.pc-filters .chip':'.game-shell .collection-page .replica-filter'})){
 for(const [part,pseudo]of [['before','::before'],['after','::after']]){
  const style=reference.rest[native][part],nodes=Object.entries(style).filter(([key])=>/^mask-(?:composite|position|mode|clip|origin)$/.test(key)).map(([prop,value])=>postcss.decl({prop,value}));
  out.append(postcss.rule({selector:local+pseudo,nodes}));
 }
}
out.append(postcss.rule({selector:'.game-shell #screen-team .pc-xp',nodes:[postcss.decl({prop:'border-radius',value:'0'})]}));
fs.writeFileSync('src/styles/team-pc-reference.css',`/* Generated by scripts/extract-team-pc-styles.mjs; native CSS SHA256 ${hash}. */\n`+out.toString());
console.log({teamPcRules:out.nodes.length});
