import fs from 'node:fs';
import postcss from 'postcss';
import {createHash} from 'node:crypto';
const bytes=fs.readFileSync('scratch/live-update-2026-11-16/app.3e06fa8ed6.css');
const hash=createHash('sha256').update(bytes).digest('hex');
if(!hash.startsWith('3e06fa8ed6'))throw Error('Inspect reference CSS changed');
const out=postcss.root();
postcss.parse(bytes).walkRules(rule=>{
 if(rule.parent.type==='atrule'&&rule.parent.name.includes('keyframes'))return;
 const selectors=rule.selectors.filter(s=>/\.(?:dexcard|dc-|mon-card|evo-chain|evo\b|statbars|xpbar|buddy-ic|buddy-sum|fam-|rpips|info-tip|mvd|shiny-mk|lock-ic)/.test(s)&&!s.includes('data-theme=light')&&!s.includes(':root'));
 if(!selectors.length)return;
 const clone=rule.clone({selector:selectors.map(s=>{
  s=s.replace(/^html\.px\s+|^\.px\s+/, '');
  if(s.startsWith('.dexcard-modal'))return '.game-shell '+s.replace('.dexcard-modal','.modal:is(.replica-inspect,.replica-detail)');
  return (s.includes('.mvd')?'.game-shell ':'.game-shell :is(.replica-inspect,.replica-detail) ')+s;
 }).join(',')});
 clone.walkDecls(d=>{d.value=d.value.replaceAll('../assets/','/assets/').replaceAll('url(assets/','url(/assets/');});
 let wrapped=clone;
 for(let p=rule.parent;p.type!=='root';p=p.parent)if(p.type==='atrule'&&['media','supports','container'].includes(p.name))wrapped=postcss.atRule({name:p.name,params:p.params,nodes:[wrapped]});
 out.append(wrapped);
});
fs.writeFileSync('src/styles/inspect-reference.css',`/* Generated by scripts/extract-inspect-styles.mjs; native v0.5.02; SHA256 ${hash}. */\n`+out.toString());
console.log({inspectRules:out.nodes.length});
